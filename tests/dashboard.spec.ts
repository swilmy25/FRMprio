import { test, expect } from '@playwright/test'
import { impact, sampleProjects, validate } from '../src/model'

test('capacity accounts for completed extras only in total scope, and future requests in demand', () => {
  expect(impact(sampleProjects[0])).toEqual({ remaining: { controls: 9, hours: 64 }, futureHours: 88, gap: 16, extraHours: 36, totalHours: 196 })
  const p = { ...sampleProjects[0], capacity: 100 }
  expect(impact(p).gap).toBe(0)
  expect(validate({ ...p, done: { ...p.done, hours: 161 } })).toContain('cannot exceed')
  expect(validate({ ...p, end: '2026-09-01' })).toContain('End date')
})
