test('project edits survive reload and update impact totals', async ({ page }) => {
  await page.getByRole('button', { name: 'Edit project' }).click()
  await page.getByLabel('Project name', { exact: true }).fill('Access controls revised')
  await page.getByLabel('Available future hours').fill('88')
  await page.getByLabel('Category', { exact: true }).fill('Technology')
  await page.getByLabel('Delivery assignments / who is working on what').fill('FRM reviews evidence; PwC validates the walkthrough.')
  await page.getByRole('button', { name: 'Save project', exact: true }).click()
  await expect(page.locator('.detail-heading h2')).toHaveText('Access controls revised')
  await expect(page.locator('.gap')).toContainText('0 hrs')
  await page.reload()
  await expect(page.locator('.detail-heading h2')).toHaveText('Access controls revised')
  await expect(page.getByText('FRM reviews evidence; PwC validates the walkthrough.')).toBeVisible()
})
test('new projects can be added and invalid planned delivery cannot be saved', async ({ page }) => {
  await page.getByRole('button', { name: 'Add project' }).click()
  await page.getByLabel('Project name', { exact: true }).fill('New assurance project')
  await page.getByRole('button', { name: 'Save project', exact: true }).click()
  await expect(page.locator('.project-row')).toHaveCount(5)
  await page.getByRole('button', { name: 'Edit project' }).click()
  await page.locator('fieldset').filter({ has: page.locator('legend', { hasText: 'Completed within plan' }) }).getByLabel('Hours', { exact: true }).fill('1')
  await page.getByRole('button', { name: 'Save project', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('cannot exceed')
})
test('export and import round-trip projects', async ({ page }) => {
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export' }).click()
  const download = await downloading
  const path = await download.path()
  expect(download.suggestedFilename()).toBe('frm-projects.json')
  page.on('dialog', d => d.accept())
  await page.locator('input[type=file]').setInputFiles(path!)
  await expect(page.getByRole('status')).toContainText('imported successfully')
  await expect(page.locator('.project-row')).toHaveCount(4)
})
